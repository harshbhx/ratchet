"""web/src/data/measured.json (what the judges page and the dashboard show as measured) is what the evidence folders give.

The file is generated by scripts/measured_numbers.py; here it is recomputed and compared, a few values are re-derived by hand from
the saved files, every section's source exists, and the Night School tile stays hidden until its evidence folder does.
"""

from __future__ import annotations

import gzip
import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("measured_numbers", ROOT / "scripts" / "measured_numbers.py")
mn = importlib.util.module_from_spec(_spec)
sys.modules["measured_numbers"] = mn
_spec.loader.exec_module(mn)

DATA = json.loads((ROOT / "web/src/data/measured.json").read_text(encoding="utf-8"))


def _j(rel):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def test_file_is_what_the_evidence_gives():
    have = (ROOT / "web/src/data/measured.json").read_text(encoding="utf-8").replace("\r\n", "\n")
    assert have == mn.render(), "run: python scripts/measured_numbers.py"


def test_every_section_has_a_real_source_and_an_iso_date():
    for name, sec in DATA.items():
        if name == "generator":
            continue
        if sec.get("present", True):
            assert (ROOT / sec["source"]).exists(), (name, sec["source"])
            assert re.fullmatch(r"\d{4}-\d{2}-\d{2}", sec["date"]), name


def test_values_recomputed_by_hand():
    nano = _j("evidence/text2sql-round2-nebius/results/results_nebius.json")["exams"]["exam1"]["nebius_retrain"]
    assert DATA["retrain"]["exams"][0]["nebius"]["agree"] == nano["agree"] == 70
    facts = _j("evidence/text2sql-round2-nebius/results/run_facts.json")
    assert DATA["retrain"]["cost_usd"] == facts["cost_usd_total_estimate"]
    cold = _j("evidence/student-endpoint-nebius/results/session2_cold_start.json")
    assert DATA["endpoint"]["cold_start_s"] == cold["seconds"]["total_until_ready"]
    assert (
        DATA["labelling"]["rounds"][1]["usd"]
        == _j("evidence/text2sql-round2/data/teacher_manifest_round2.json")["spent_usd_estimate"]
    )
    # The smoke run's request count is the number of rows in its request log.
    log = gzip.decompress((ROOT / "evidence/live-smoke-2026-10-23/requests.ndjson.gz").read_bytes()).decode().splitlines()
    assert DATA["smoke"]["requests"] <= len([ln for ln in log if ln.strip()])
    for run in DATA["scout"]["runs"]:
        rec = json.loads((ROOT / run["file"]).read_text(encoding="utf-8"))
        assert run["recorded_at"] == rec["recorded_at"] and run["question"] == rec["question"]
        assert (
            sum(e["cost_usd"] or 0 for e in rec["events"] if e["type"] == "step") == run["cost_usd"]
            or abs(sum(e["cost_usd"] or 0 for e in rec["events"] if e["type"] == "step") - run["cost_usd"]) < 1e-6
        )


def test_exam_scores_are_the_checked_exam_files():
    e = _j("web/src/data/exams.json")
    for x in DATA["exams"]["exams"]:
        for s in x["scores"]:
            assert e["scores"][x["id"]][s["model"]]["agree"] == s["agree"]
    t = _j("web/src/data/toolcall.json")
    for x in DATA["toolcall"]["exams"]:
        for s in x["scores"]:
            assert t["exams"][x["id"]]["scores"][s["model"]]["agree"] == s["agree"]


def test_nightschool_is_hidden_until_its_evidence_exists():
    present = (ROOT / "evidence/nightschool-nebius").is_dir()
    assert DATA["nightschool"]["present"] is present
    if not present:
        assert set(DATA["nightschool"]) == {"present", "source"}  # no number, no date, nothing to show


def test_no_demo_or_simulation_wording_in_the_data():
    text = json.dumps(DATA).lower()
    assert "demo" not in text and "simulat" not in text
